    /**
     * استرجاع مباشر لفقرة مطابقة بدقة للكلمات المفتاحية
     */
    fun findByKeyword(query: String): List<BookKnowledgeChunk> {
        val q = query.trim().lowercase()
        return chunks.filter { chunk ->
            chunk.keywords.any { q.contains(it.lowercase()) } ||
            chunk.content.contains(q) ||
            chunk.topic.contains(q)
        }
    }
